def check_retrieval_score(state: State) -> dict:
    """Keep chunks that pass the vector threshold; rescue one by keywords if none do."""
    try:
        docs = state.get("docs") or []
        scores = state.get("retrieval_scores") or []
        hybrids = state.get("hybrid_scores") or [0.0] * len(docs)
        score_type = state.get("score_type", "distance")

        kept, kept_h = [], []
        for doc, score, hyb in zip(docs, scores, hybrids):
            ok = (
                score <= SIMILARITY_THRESHOLD_FIASS
                if score_type == "distance"
                else score >= SIMILARITY_THRESHOLD_PINECONE
            )
            if ok:
                kept.append(doc)
                kept_h.append(hyb)

        if not kept and docs:
            keywords = _extract_keywords(_search_text(state))
            overlaps = [_compute_keyword_overlap(d.page_content, keywords) for d in docs]
            best = max(range(len(docs)), key=lambda i: overlaps[i])
            if overlaps[best] >= LEXICAL_FALLBACK_MIN:
                kept = [docs[best]]
                kept_h = [hybrids[best] if best < len(hybrids) else 0.0]
                logging.info(f"Vector threshold rejected all; lexical rescue (overlap={overlaps[best]:.2f}).")

        confidence = round(sum(kept_h) / len(kept_h), 3) if kept_h else 0.0
        logging.info(f"Relevant docs: {len(kept)}/{len(docs)} | confidence={confidence}")
        return {"relevant_docs": kept, "retrieval_confidence": confidence}
    except Exception as e:
        logging.error(f"check_retrieval_score failed: {e}")
        raise CustomException(e, sys)


def route_after_retrieval_score(
    state: State,
) -> Literal["generate_from_context", "query_optimizer", "web_search", "no_answer_found"]:
    if state.get("relevant_docs"):
        return "generate_from_context"
    if state.get("query_tries", 0) < MAX_QUERY_TRIES:
        return "query_optimizer"
    if WEB_FALLBACK_ON_RETRIEVAL_FAIL:
        return "web_search"
    return "no_answer_found"


