def _describe_image(image: str) -> str:
    """`image` = http(s) URL, data URL, or raw base64 (assumed PNG)."""
    url = image if image.startswith(("http://", "https://", "data:")) else f"data:image/png;base64,{image}"
    msg = HumanMessage(
        content=[
            {"type": "text", "text": image_describe_prompt},
            {"type": "image_url", "image_url": {"url": url}},
        ]
    )
    return str(llm.invoke([msg]).content).strip()


def prepare_query(state: State) -> dict:
    """
    First node of every turn.
    1) Resets all per-turn fields (the checkpointer would otherwise leak
       retries / docs / answer from the previous turn).
    2) Image query -> text description.
    3) Follow-up question -> standalone question.
    """
    question = (state.get("question") or "").strip()
    image = state.get("query_image")
    history = state.get("history") or []

    image_description = ""
    if image:
        try:
            image_description = _describe_image(image)
            logging.info(f"Image described: {image_description[:200]}")
        except Exception as e:
            logging.error(f"Image description failed: {e}")

    standalone = question or image_description
    if history or image_description:
        try:
            res: StandaloneQuestion = condense_llm.invoke(
                condense_prompt.format_messages(
                    history=_format_history(history),
                    image_description=image_description or "(none)",
                    question=question or "(no text, image only)",
                )
            )
            standalone = res.standalone_question.strip() or standalone
        except Exception as e:
            logging.error(f"Condense failed, using fallback: {e}")
            standalone = f"{question} {image_description}".strip()

    logging.info(f"Question: {question!r} -> standalone: {standalone!r}")

    return {
        # ---- per-turn reset ----
        "retries": 0,
        "rewrite_tries": 0,
        "query_tries": 0,
        "retrieval_query": "",
        "optimized_query": "",
        "keywords": [],
        "entities": [],
        "docs": [],
        "retrieval_scores": [],
        "hybrid_scores": [],
        "relevant_docs": [],
        "context": "",
        "answer": "",
        "issup": None,
        "isuse": None,
        "evidence": [],
        "use_reason": "",
        "sources": [],
        "citations": [],
        "media": [],
        "web_results": "",
        "confidence_score": 0.0,
        "retrieval_confidence": 0.0,
        "evaluation": None,
        "cache_hit": False,
        "cache_similarity": 0.0,
        "cache_saved": False,
        "route": "",
        # ---- resolved query ----
        "standalone_question": standalone,
        "image_description": image_description,
        "query_image": None,   # consume it so it never leaks into the next turn
        "cache_bypass": bool(state.get("skip_cache")),   # "regenerate" button
        "skip_cache": False,                             # consume so it never leaks
    }


