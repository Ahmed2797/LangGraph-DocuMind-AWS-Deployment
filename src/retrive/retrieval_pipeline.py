def _detect_score_type(vectorstore) -> str:
    """FAISS / Chroma return DISTANCE (lower better); Pinecone returns SIMILARITY."""
    name = type(vectorstore).__name__.lower()
    return "distance" if any(k in name for k in ("faiss", "chroma")) else "similarity"


def _semantic_part(score: Optional[float], score_type: str) -> float:
    if score is None:
        return 0.5
    s = float(score)
    if score_type == "distance":
        return 1.0 / (1.0 + max(s, 0.0))
    return min(max(s, 0.0), 1.0)


def rerank_documents(docs_with_scores, query: str, score_type: str = "distance") -> List[dict]:
    """Blend vector score (0.7) with keyword coverage (0.3)."""
    keywords = _extract_keywords(query)
    ranked = []
    for doc, score in docs_with_scores:
        semantic = _semantic_part(score, score_type)
        lexical = _compute_keyword_overlap(doc.page_content, keywords)
        ranked.append(
            {
                "doc": doc,
                "score": float(score) if score is not None else 0.0,
                "hybrid_score": 0.7 * semantic + 0.3 * lexical,
                "lexical_part": lexical,
            }
        )
    ranked.sort(key=lambda r: r["hybrid_score"], reverse=True)
    return ranked


def build_retrieve_node(vectorstore, k: int = 5):
    """Factory: returns the `retrieve` node bound to a FAISS / Pinecone vector store."""
    score_type = _detect_score_type(vectorstore)

    def retrieve(state: State) -> dict:
        try:
            query = _search_text(state)
            pairs = vectorstore.similarity_search_with_score(query, k=k)
            ranked = rerank_documents(pairs, query, score_type)
            logging.info(f"Retrieved {len(ranked)} docs for {query!r} ({score_type}).")
            return {
                "docs": [r["doc"] for r in ranked],
                "retrieval_scores": [r["score"] for r in ranked],
                "hybrid_scores": [r["hybrid_score"] for r in ranked],
                "score_type": score_type,
            }
        except Exception as e:
            logging.error(f"Retrieval failed: {e}")
            raise CustomException(e, sys)

    return retrieve


