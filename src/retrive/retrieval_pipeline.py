def _flatten_tool_result(raw: Any) -> str:
    """MCP / LangChain tools return str, list of blocks, tuple, dict or message."""
    if raw is None:
        return ""
    if isinstance(raw, str):
        return raw
    if isinstance(raw, dict):
        if isinstance(raw.get("text"), str):
            return raw["text"]
        return json.dumps(raw, default=str)
    if isinstance(raw, (list, tuple)):
        return "\n".join(p for p in (_flatten_tool_result(x) for x in raw) if p)
    content = getattr(raw, "content", None)
    if content is not None:
        return _flatten_tool_result(content)
    text = getattr(raw, "text", None)
    return text if isinstance(text, str) else str(raw)


_TEXT_RESULT_RE = re.compile(
    r"Title:\s*(?P<title>.*?)\s*\n\s*URL:\s*(?P<url>\S+)\s*\n\s*Content:\s*(?P<content>.*?)"
    r"(?=\n\s*Title:|\n\s*Images?\s*:|\Z)",
    re.S | re.I,
)
_IMG_LINE_RE = re.compile(r"^\s*(?:[-*]\s*)?(?:Image\s*\d*\s*:\s*)?(https?://\S+)\s*$", re.I)


def _parse_text_images(text: str) -> List[dict]:
    parts = re.split(r"\n\s*Images?\s*:\s*\n?", text, maxsplit=1, flags=re.I)
    section = parts[1] if len(parts) > 1 else ""
    images: List[dict] = []
    for line in section.splitlines():
        m = _IMG_LINE_RE.match(line)
        if m:
            images.append({"url": m.group(1).rstrip(".,)"), "caption": ""})
        elif images and re.match(r"\s*(description|caption)\s*:", line, re.I):
            images[-1]["caption"] = line.split(":", 1)[1].strip()
    if not images:   # last resort: any URL that looks like an image file
        images = [{"url": u.rstrip(".,)"), "caption": ""} for u in _URL_RE.findall(text) if _IMG_EXT_RE.search(u)]
    return images


def _parse_web_result(raw: Any) -> tuple[List[dict], List[dict], str]:
    """-> (results[{title,url,content}], images[{url,caption}], flat_text)"""
    text = _flatten_tool_result(raw)
    results: List[dict] = []
    images: List[dict] = []

    data = None
    if text.strip().startswith("{"):
        try:
            data = json.loads(text)
        except Exception:
            data = None

    if isinstance(data, dict):                       # structured JSON (Tavily API style)
        for r in data.get("results") or []:
            results.append({"title": r.get("title", ""), "url": r.get("url", ""), "content": r.get("content", "")})
        for im in data.get("images") or []:
            if isinstance(im, str):
                images.append({"url": im, "caption": ""})
            elif isinstance(im, dict):
                images.append({"url": im.get("url", ""), "caption": im.get("description", "")})
    else:                                            # formatted text (Tavily MCP style)
        for m in _TEXT_RESULT_RE.finditer(text):
            results.append({"title": m["title"].strip(), "url": m["url"].strip(), "content": m["content"].strip()})
        images = _parse_text_images(text)

    seen, clean = set(), []
    for im in images:
        url = str(im.get("url", "")).strip()
        if url.startswith(("http://", "https://")) and url not in seen:
            seen.add(url)
            clean.append({"url": url, "caption": str(im.get("caption", "")).strip()})
    return results, clean[:MAX_MEDIA_ITEMS], text


async def _run_web_search(query: str) -> Any:
    """Call the Tavily MCP tool once, asking for images. MCP is initialised lazily, once."""
    if getattr(mcp, "search_tool", None) is None:
        await mcp.initialize_mcp()

    args = {
        "query": query,
        "max_results": WEB_MAX_RESULTS,
        "include_images": True,
        "include_image_descriptions": True,
    }
    try:
        return await mcp.search_tool.ainvoke(args)
    except Exception as e:   # tool schema may not accept the image flags
        logging.warning(f"Search with images failed ({e}); retrying with query only.")
        return await mcp.search_tool.ainvoke({"query": query})


async def web_search_node(state: State) -> dict:
    """Web search -> grounded text answer + images from the same search."""
    question = _q(state)
    try:
        raw = await _run_web_search(_search_text(state))
        results, images, flat = _parse_web_result(raw)
        logging.info(f"Web: {len(results)} results, {len(images)} images.")

        if results:
            blocks = [
                f"[{i}] {r['title']} ({r['url']})\n{r['content'][:900]}"
                for i, r in enumerate(results, 1)
            ]
            results_text = "\n\n".join(blocks)
        else:                                        # parse failed: give the model the raw text
            results_text = flat[:6000]

        if not results_text.strip():
            return {**_empty_answer_payload("Web search returned no usable results."), "web_results": ""}

        out = llm.invoke(web_answer_prompt.format_messages(question=question, results=results_text))

        media = [
            {"type": "image", "url": im["url"], "caption": im["caption"], "source": "web"}
            for im in images
        ]
        return {
            "answer": str(out.content),
            "sources": [r["url"] for r in results if r["url"]],
            "citations": [
                {"source": r["url"] or r["title"], "snippet": " ".join(r["content"].split())[:240]}
                for r in results
            ],
            "media": media,
            "web_results": results_text[:4000],
            "context": "",
            "confidence_score": 0.0,
        }
    except Exception as e:
        logging.error(f"web_search_node failed: {e}")
        return {**_empty_answer_payload("Web search is currently unavailable. Please try again."), "web_results": ""}


