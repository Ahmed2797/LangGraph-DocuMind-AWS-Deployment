_SUPPORT_FACTOR = {"fully_supported": 1.0, "partially_supported": 0.7, "no_support": 0.3}


def check_grounded(state: State) -> dict:
    """Groundedness critic (was `is_sup`)."""
    docs = state.get("relevant_docs") or []
    context = "\n\n".join(
        f"[Source: {_doc_source(d)}]\n{d.page_content}" for d in docs
    )
    try:
        decision: IsSUPDecision = issup_llm.invoke(
            issup_prompt.format_messages(
                question=_q(state), answer=state.get("answer", ""), context=context
            )
        )
        verdict, evidence = decision.issup, list(decision.evidence)
    except Exception as e:
        logging.error(f"check_grounded failed, treating as partially supported: {e}")
        verdict, evidence = "partially_supported", []

    logging.info(f"Grounded verdict: {verdict}")
    base = state.get("retrieval_confidence", 0.0)
    return {
        "issup": verdict,
        "evidence": evidence,
        "confidence_score": round(base * _SUPPORT_FACTOR.get(verdict, 0.5), 3),
    }


def route_after_grounded(
    state: State,
) -> Literal["accept_answer", "revise_answer", "no_answer_found"]:
    verdict = state.get("issup")
    retries = state.get("retries", 0)
    logging.info(f"Route after grounded: {verdict} | retries={retries}")

    if verdict == "fully_supported":
        return "accept_answer"
    if retries >= MAX_REVISE_TRIES:
        # out of retries: keep a partially supported answer, drop an unsupported one
        return "accept_answer" if verdict == "partially_supported" else "no_answer_found"
    return "revise_answer"


def revise_answer(state: State) -> dict:
    out = llm.invoke(
        revise_prompt.format_messages(
            question=_q(state),
            answer=state.get("answer", ""),
            context=state.get("context", ""),
        )
    )
    return {"answer": str(out.content), "retries": state.get("retries", 0) + 1}


def check_useful(state: State) -> dict:
    """Usefulness critic (was `is_use`)."""
    try:
        decision: IsUSEDecision = isuse_llm.invoke(
            isuse_prompt.format_messages(question=_q(state), answer=state.get("answer", ""))
        )
        verdict, reason = decision.isuse, decision.use_reason
    except Exception as e:
        logging.error(f"check_useful failed, treating as useful: {e}")
        verdict, reason = "useful", ""
    logging.info(f"Useful verdict: {verdict} ({reason})")
    return {"isuse": verdict, "use_reason": reason}


def route_after_useful(
    state: State,
) -> Literal["evaluate_answer", "rewrite_question", "no_answer_found"]:
    if state.get("isuse") == "useful":
        return "evaluate_answer"
    if state.get("rewrite_tries", 0) >= MAX_REWRITE_TRIES:   # default 0, not MAX
        return "no_answer_found"
    return "rewrite_question"


def rewrite_question(state: State) -> dict:
    """Rewrite the retrieval query and restart the answer cycle."""
    try:
        decision: RewriteDecision = rewrite_llm.invoke(
            rewrite_for_retrieval_prompt.format_messages(
                question=_q(state),
                retrieval_query=state.get("retrieval_query", ""),
                answer=state.get("answer", ""),
            )
        )
        new_query = decision.retrieval_query.strip() or _q(state)
    except Exception as e:
        logging.error(f"rewrite_question failed: {e}")
        new_query = _q(state)

    return {
        "retrieval_query": new_query,
        "rewrite_tries": state.get("rewrite_tries", 0) + 1,
        "retries": 0,            # fresh revise budget for the new attempt
        "issup": None,
        "answer": "",
        "docs": [],
        "hybrid_scores": [],
        "retrieval_scores": [],
        "relevant_docs": [],
        "context": "",
    }


