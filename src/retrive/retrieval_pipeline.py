_TOKEN_RE = re.compile(r"\w+", re.UNICODE)
_URL_RE = re.compile(r"https?://[^\s\"'<>\]\)]+")
_IMG_EXT_RE = re.compile(r"\.(png|jpe?g|gif|webp|avif|bmp)(\?|#|$)", re.I)


def _tokens(text: Any) -> List[str]:
    return _TOKEN_RE.findall(str(text or "").lower())


def _extract_keywords(question: str) -> List[str]:
    seen, out = set(), []
    for tok in _tokens(question):
        if len(tok) > 2 and tok not in _STOPWORDS and tok not in seen:
            seen.add(tok)
            out.append(tok)
    return out


def _compute_keyword_overlap(doc_text: str, keywords: List[str]) -> float:
    """Fraction of keywords present as WHOLE words in the document."""
    if not keywords:
        return 0.0
    doc_tokens = set(_tokens(doc_text))
    return sum(1 for k in keywords if k in doc_tokens) / len(keywords)


def _extract_best_snippet(doc_text: str, keywords: List[str], max_chars: int = 240) -> str:
    """Snippet from the ORIGINAL text (keeps case), centred on a keyword hit."""
    flat = " ".join(str(doc_text or "").split())
    for kw in keywords:
        m = re.search(rf"\b{re.escape(kw)}\b", flat, flags=re.I)
        if m:
            start = max(0, m.start() - 80)
            return flat[start:start + max_chars].strip()
    return flat[:max_chars]


