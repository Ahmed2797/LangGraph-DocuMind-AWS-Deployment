def _cache_kwargs(project_id: Optional[str]) -> dict:
    """Cache vectors live in namespace 'cache-<project>' so they can never be
    mistaken for document chunks, even if both use the same Pinecone index."""
    if not project_id:
        return {}
    return {"namespace": "cache-" + str(project_id).lower().replace("_", "-")}


def _numbers(text: str) -> frozenset:
    """Numbers/years in a question. 'revenue 2023' and 'revenue 2024' are
    semantically close but need DIFFERENT answers, so they must not match."""
    return frozenset(re.findall(r"\d+(?:[.,]\d+)?", str(text or "")))


@traceable(name="Search Semantic Cache Index")
def search_semantic_cache(question: str, namespace: Optional[str] = None) -> Optional[dict]:
    """Return cached payload or None. NEVER raises — cache is optional.
    `namespace` = project id, so one project never sees another project's answers."""
    try:
        embedding = create_embedding(question)
        index = create_pincone_database(index_name=INDEX_NAME_CACHE_MEMORY)
        kwargs = _cache_kwargs(namespace)
        result = index.query(
            vector=embedding,
            top_k=CACHE_TOP_K,
            include_metadata=True,
            # expired / old-version / old-format entries are never returned
            filter={
                "cache_version": {"$eq": CACHE_VERSION},
                "created_at": {"$gte": time.time() - CACHE_TTL_SECONDS},
            },
            **kwargs,
        )

        for match in result.matches or []:        # sorted by score, best first
            if match.score < CACHE_THRESHOLD:
                break
            meta = match.metadata or {}
            if _numbers(meta.get("question", "")) != _numbers(question):
                logging.info("Cache candidate skipped: numbers/years differ.")
                continue
            payload = json.loads(meta.get("payload", "{}") or "{}")
            return {
                "answer": meta.get("answer", ""),
                "evaluation": json.loads(meta.get("evaluation", "{}") or "{}"),
                "sources": payload.get("sources", []),
                "citations": payload.get("citations", []),
                "media": payload.get("media", []),
                "similarity": match.score,
            }

        logging.info("Semantic cache miss.")
        return None
    except Exception as e:
        logging.error(f"Semantic cache search failed (treated as miss): {e}")
        return None


def clear_project_cache(project_id: str) -> bool:
    """
    CALL THIS whenever a project's documents change (upload, delete, re-index).
    Otherwise old answers keep being served for the new documents.
    """
    kw = _cache_kwargs(project_id)
    ns = kw.get("namespace", "")
    try:
        index = create_pincone_database(index_name=INDEX_NAME_CACHE_MEMORY)
        index.delete(delete_all=True, **kw)
        logging.info(f"Semantic cache cleared for project {ns}.")
        return True
    except Exception as e:
        logging.error(f"Clearing semantic cache failed for {ns}: {e}")
        return False


@traceable(name="Save Semantic Cache Index")
def save_semantic_cache(
    question: str,
    answer: str,
    evaluation: Optional[dict] = None,
    sources: Optional[list] = None,
    citations: Optional[list] = None,
    media: Optional[list] = None,
    namespace: Optional[str] = None,
) -> bool:
    """Upsert Q/A into cache. NEVER raises — a cache error must not lose the answer."""
    try:
        embedding = create_embedding(question)
        index = create_pincone_database(index_name=INDEX_NAME_CACHE_MEMORY)
        payload = {
            "sources": sources or [],
            "citations": (citations or [])[:5],
            "media": _media_for_cache(media or []),
        }
        kwargs = _cache_kwargs(namespace)
        index.upsert(
            **kwargs,
            vectors=[
                {
                    "id": str(uuid.uuid4()),
                    "values": embedding,
                    "metadata": {
                        "question": question,
                        "answer": answer,
                        "evaluation": json.dumps(evaluation or {}, default=str),
                        "payload": json.dumps(payload, default=str),
                        "cache_version": CACHE_VERSION,
                        "created_at": time.time(),
                    },
                }
            ]
        )
        logging.info("Answer saved to semantic cache.")
        return True
    except Exception as e:
        logging.error(f"Semantic cache save failed (ignored): {e}")
        return False


def check_semantic_cache_node(state: State, namespace: Optional[str] = None) -> dict:
    """Image queries skip the cache (same text + different image = different answer)."""
    if state.get("cache_bypass"):
        logging.info("cache_bypass -> semantic cache skipped (fresh answer requested).")
        return {"cache_hit": False, "cache_similarity": 0.0}
    if state.get("image_description"):
        logging.info("Image query -> semantic cache skipped.")
        return {"cache_hit": False, "cache_similarity": 0.0}

    cached = search_semantic_cache(_q(state), namespace=namespace)
    if cached is None:
        return {"cache_hit": False, "cache_similarity": 0.0}

    logging.info(f"Semantic cache HIT | similarity={cached['similarity']:.3f}")
    return {
        "cache_hit": True,
        "cache_similarity": cached["similarity"],
        "answer": cached["answer"],
        "evaluation": cached["evaluation"],
        "sources": cached["sources"],
        "citations": cached["citations"],
        "media": cached["media"],
    }


def route_after_cache(state: State) -> Literal["cached_answer", "continue_rag"]:
    return "cached_answer" if state.get("cache_hit") else "continue_rag"


def save_cache_node(state: State, namespace: Optional[str] = None) -> dict:
    """Only RELIABLE, evaluated RAG answers are cached."""
    evaluation = state.get("evaluation") or {}
    if not evaluation.get("is_reliable", False):
        logging.info("Answer not marked reliable -> not cached.")
        return {"cache_saved": False}

    saved = save_semantic_cache(
        question=_q(state),
        answer=state.get("answer", ""),
        evaluation=evaluation,
        sources=state.get("sources"),
        citations=state.get("citations"),
        media=state.get("media"),
        namespace=namespace,
    )
    return {"cache_saved": saved}


