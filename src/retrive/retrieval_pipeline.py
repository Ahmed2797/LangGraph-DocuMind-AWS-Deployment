# Metadata keys that ingestion may use. Add your own keys here if different.
_MEDIA_KEYS = {
    "image": ("images", "image", "image_path", "image_paths", "image_url", "figure", "figures"),
    "chart": ("charts", "chart", "chart_path", "chart_url"),
    "table": ("tables", "table", "table_markdown", "table_html"),
}
_MEDIA_ORDER = {"image": 0, "chart": 1, "table": 2}


def _as_list(value: Any) -> list:
    if value is None:
        return []
    if isinstance(value, (list, tuple, set)):
        return list(value)
    return [value]


def _make_media_item(kind: str, value: Any, doc) -> Optional[dict]:
    meta = getattr(doc, "metadata", None) or {}
    item = {
        "type": kind,
        "source": _doc_source(doc),
        "page": meta.get("page"),
        "caption": meta.get(f"{kind}_caption") or meta.get("caption") or "",
    }
    if isinstance(value, dict):
        for key in ("url", "path", "content", "caption", "page", "type"):
            if value.get(key) not in (None, ""):
                item[key] = value[key]
    elif isinstance(value, str) and value.strip():
        v = value.strip()
        if v.startswith(("http://", "https://", "data:")):
            item["url"] = v
        elif kind == "table" and not _IMG_EXT_RE.search(v):
            item["content"] = v          # markdown / html table text
        else:
            item["path"] = v
    else:
        return None
    if not any(k in item for k in ("url", "path", "content")):
        return None
    return item


def _media_key(item: dict) -> tuple:
    ref = item.get("url") or item.get("path") or str(item.get("content", ""))[:80]
    return (item.get("type"), ref)


def _collect_media_from_docs(docs) -> List[dict]:
    """Images / charts / tables stored in chunk metadata of the used documents."""
    items, seen = [], set()

    def add(item):
        if item and _media_key(item) not in seen:
            seen.add(_media_key(item))
            items.append(item)

    for doc in docs or []:
        meta = getattr(doc, "metadata", None) or {}
        # ---- format written by index_files(): separate image / table records ----
        doc_type = meta.get("type")
        if doc_type == "image":
            for f in _as_list(meta.get("files") or meta.get("file")):
                add({
                    "type": "image",
                    "path": str(f),
                    "url": f"{IMAGE_URL_PREFIX}/{f}",
                    "source": _doc_source(doc),
                    "page": meta.get("page"),
                    "caption": "",
                })
        elif doc_type == "table":
            add({
                "type": "table",
                "content": doc.page_content,
                "source": _doc_source(doc),
                "page": meta.get("page"),
                "caption": "",
            })

        for kind, keys in _MEDIA_KEYS.items():
            for key in keys:
                for value in _as_list(meta.get(key)):
                    add(_make_media_item(kind, value, doc))
        for value in _as_list(meta.get("media")):      # generic list of dicts
            if isinstance(value, dict):
                add(_make_media_item(str(value.get("type", "image")), value, doc))

    items.sort(key=lambda it: _MEDIA_ORDER.get(it["type"], 9))
    return items[:MAX_MEDIA_ITEMS]


def _media_for_cache(media: List[dict]) -> List[dict]:
    """Keep cache payload small: drop inline base64, trim table text."""
    out = []
    for m in media or []:
        if str(m.get("url", "")).startswith("data:"):
            continue
        m = dict(m)
        if "content" in m:
            m["content"] = str(m["content"])[:1500]
        out.append(m)
    return out[:MAX_MEDIA_ITEMS]


