@traceable(name="Evaluate Answer Engine")
def evaluate_answer_node(state: State) -> dict:
    """Quality metrics. A failure here must not break the user's answer."""
    try:
        chunks = [
            {
                "source": _doc_source(d),
                "page": (d.metadata or {}).get("page"),
                "chunk_id": (d.metadata or {}).get("chunk_id"),
                "content": d.page_content,
            }
            for d in (state.get("relevant_docs") or [])
        ]
        evaluation = evaluate_answer(
            question=_q(state), answer=state.get("answer", ""), context_chunks=chunks
        )
        logging.info(
            f"Eval | hallucination={evaluation.get('hallucination', {}).get('score')} "
            f"groundedness={evaluation.get('groundedness', {}).get('score')} "
            f"quality={evaluation.get('overall_quality')} reliable={evaluation.get('is_reliable')}"
        )
        return {"evaluation": evaluation}
    except Exception as e:
        logging.error(f"Evaluation failed (answer still returned): {e}")
        return {"evaluation": {"error": str(e), "is_reliable": False}}


def finalize_response(state: State) -> dict:
    """Every path ends here: store the turn in chat history for follow-up questions."""
    history = list(state.get("history") or [])
    history.append(
        {
            "user": (state.get("question") or "").strip() or "(image)",
            "assistant": str(state.get("answer", ""))[:600],
        }
    )
    return {"history": history[-MAX_HISTORY_TURNS:]}

